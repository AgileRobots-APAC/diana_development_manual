#!/usr/bin/env python3
"""Generate the searchable error-code reference from the checked-in manual data."""
from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "api_v3_3_0.json"
OUTPUT = ROOT / "docs" / "zh_CN" / "reference" / "error_codes.md"
EN_OUTPUT = ROOT / "docs" / "en" / "reference" / "error_codes.md"


def description(text: str) -> str:
    return (
        text.replace("尚未initSrv", "尚未完成服务初始化")
        .replace("不能 moveJ", "不能执行关节运动")
        .replace("ServoJ轨迹规划失败", "关节在线伺服轨迹规划失败")
        .replace("ServoL轨迹规划失败", "笛卡尔在线伺服轨迹规划失败")
    )


GENERATED_NOTICE = (
    "<!-- 本文件由 scripts/generate_error_codes.py 根据 data/api_v3_3_0.json 自动生成，"
    "每次构建都会覆盖；请修改数据或脚本，不要手工编辑。 -->\n"
    "<!-- Generated by scripts/generate_error_codes.py from data/api_v3_3_0.json; "
    "overwritten on every build. Edit the data or the script, not this file. -->\n\n"
)


def main() -> None:
    errors = json.loads(DATA.read_text(encoding="utf-8")).get("error_codes", [])
    rows = ["| 宏定义 | 错误码 | 说明 | 手册页 |", "|---|---:|---|---:|"]
    rows.extend(
        f"| `{item['macro'] or '-'}` | `{item['code']}` | {description(item['description'])} | {item['manual_page']} |"
        for item in errors
    )
    OUTPUT.write_text(
        GENERATED_NOTICE + """# 错误码

本页从 V3.3.0 手册附件 A 的错误码表结构化整理，共 **%d** 条。V3.4.0 手册的附件 A 内容相同，表中的手册页码为 V3.3.0 手册的页码，在 V3.4.0 手册中整体后移 2 页。

诊断流程请参见[故障排查](troubleshooting.md)。其中，`ERROR_CODE_JOINT_REGIST_ERROR (-2001)` 和 `ERROR_CODE_NOT_ALL_AT_OP_STATE (-2205)` 按手册要求需调用 `holdBrake()` 合抱闸或重启硬件。

<div class=\"api-filter\">
  <input id=\"api-table-filter\" type=\"search\" placeholder=\"输入错误码、宏定义或说明进行筛选，例如 -2202 / COLLISION\" aria-label=\"筛选错误码\" />
  <p class=\"api-filter-status\" aria-live=\"polite\"></p>
</div>

%s

```{important}
手册特别注明：`ERROR_CODE_JOINT_REGIST_ERROR (-2001)` 和 `ERROR_CODE_NOT_ALL_AT_OP_STATE (-2205)` 需要通过 `holdBrake()` 合抱闸或重启硬件来清除。
```
""" % (len(errors), "\n".join(rows)),
        encoding="utf-8",
    )
    en_rows = ["| Macro | Error code | Description in the V3.3.0 Chinese source | Manual page |", "|---|---:|---|---:|"]
    en_rows.extend(
        f"| `{item['macro'] or '-'}` | `{item['code']}` | {description(item['description'])} | {item['manual_page']} |"
        for item in errors
    )
    EN_OUTPUT.write_text(
        GENERATED_NOTICE + """# Error Codes

This searchable table contains all **%d** error-code entries from appendix A of the V3.3.0 manual. Appendix A of the V3.4.0 manual is identical; the manual page numbers in the table are those of the V3.3.0 manual and are shifted back by 2 pages in the V3.4.0 manual. Error codes and macro names are language-independent. The descriptions retain the official Chinese source wording to avoid changing safety or recovery semantics without an SDK release-approved translation.

For diagnostic workflow, see [Troubleshooting](troubleshooting.md). In particular, `ERROR_CODE_JOINT_REGIST_ERROR (-2001)` and `ERROR_CODE_NOT_ALL_AT_OP_STATE (-2205)` require `holdBrake()` or a hardware restart according to the manual.

<div class="api-filter">
  <input id="api-table-filter" type="search" placeholder="Filter by error code, macro, or description, e.g. -2202 / COLLISION" aria-label="Filter error codes" />
  <p class="api-filter-status" aria-live="polite"></p>
</div>

%s

```{important}
The manual specifically notes that `ERROR_CODE_JOINT_REGIST_ERROR (-2001)` and `ERROR_CODE_NOT_ALL_AT_OP_STATE (-2205)` must be cleared by calling `holdBrake()` to engage the brakes or by restarting the hardware.
```
""" % (len(errors), "\n".join(en_rows)),
        encoding="utf-8",
    )
    print(f"generated {len(errors)} error codes")


if __name__ == "__main__":
    main()
